// Content Security Policy — intentionally strict, no inline scripts.
// Styles need 'unsafe-inline' for Next.js injected styles; scripts do not.
const csp = [
  "default-src 'self'",
  "base-uri 'self'",
  "object-src 'none'",
  "frame-ancestors 'none'",
  "form-action 'self'",
  "img-src 'self' data: https:",
  "font-src 'self' https://fonts.gstatic.com data:",
  "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com",
  // No external scripts by default. Add analytics domains here only if self-hosted/minimal.
  "script-src 'self'",
  "connect-src 'self' https://api.github.com",
  'upgrade-insecure-requests',
].join('; ');

